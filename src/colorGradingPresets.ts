function clonePoints(pts?: CurvePoint[]): CurvePoint[] {
  return pts ? pts.map((p) => ({ x: p.x, y: p.y })) : [{ x: 0, y: 0 }, { x: 1, y: 1 }];
}

export function createStateFromPreset(preset: CinematicGradePreset): ColorGradingState {
  const s = preset.state;
  return {
    ...DEFAULT_COLOR_GRADING_STATE,
    presetId: preset.id,
    presetIntensity: 100,
    brightness: s.brightness ?? 0,
    exposure: s.exposure ?? 0,
    contrast: s.contrast ?? 0,
    highlights: s.highlights ?? 0,
    shadows: s.shadows ?? 0,
    whites: s.whites ?? 0,
    blacks: s.blacks ?? 0,
    gamma: s.gamma ?? 1.0,
    saturation: s.saturation ?? 0,
    temperature: s.temperature ?? 0,
    tint: s.tint ?? 0,
    hueShift: s.hueShift ?? 0,
    hslSaturation: s.hslSaturation ?? 0,
    hslLightness: s.hslLightness ?? 0,
    redAdjust: s.redAdjust ?? 0,
    greenAdjust: s.greenAdjust ?? 0,
    blueAdjust: s.blueAdjust ?? 0,
    vignette: s.vignette ?? 0,
    grain: s.grain ?? 0,
    sharpness: s.sharpness ?? 0,
    curves: {
      master: clonePoints(s.curves?.master),
      red: clonePoints(s.curves?.red),
      green: clonePoints(s.curves?.green),
      blue: clonePoints(s.curves?.blue),
    },
    wheels: {
      lift: { ...(s.wheels?.lift ?? { x: 0, y: 0, luma: 0 }) },
      gamma: { ...(s.wheels?.gamma ?? { x: 0, y: 0, luma: 0 }) },
      gain: { ...(s.wheels?.gain ?? { x: 0, y: 0, luma: 0 }) },
    },
  };
}

/**
 * Computes effective ColorGradingState scaled smoothly by `presetIntensity` (0..100).
 * When intensity < 100, all grading parameters interpolate linearly toward neutral baseline.
 */
export function resolveEffectiveColorGradingState(state: ColorGradingState): ColorGradingState {
  const t = Math.max(0, Math.min(1, state.presetIntensity / 100));
  if (t >= 0.999) return state;

  const lerp = (neutral: number, target: number) => neutral + (target - neutral) * t;
  const lerpPoints = (pts: CurvePoint[]): CurvePoint[] =>
    pts.map((p) => ({
      x: p.x,
      y: p.x + (p.y - p.x) * t,
    }));

  return {
    ...state,
    brightness: lerp(0, state.brightness),
    exposure: lerp(0, state.exposure),
    contrast: lerp(0, state.contrast),
    highlights: lerp(0, state.highlights),
    shadows: lerp(0, state.shadows),
    whites: lerp(0, state.whites),
    blacks: lerp(0, state.blacks),
    gamma: lerp(1.0, state.gamma),
    saturation: lerp(0, state.saturation),
    temperature: lerp(0, state.temperature),
    tint: lerp(0, state.tint),
    hueShift: lerp(0, state.hueShift),
    hslSaturation: lerp(0, state.hslSaturation),
    hslLightness: lerp(0, state.hslLightness),
    redAdjust: lerp(0, state.redAdjust),
    greenAdjust: lerp(0, state.greenAdjust),
    blueAdjust: lerp(0, state.blueAdjust),
    vignette: lerp(0, state.vignette),
    grain: lerp(0, state.grain),
    sharpness: lerp(0, state.sharpness),
    curves: {
      master: lerpPoints(state.curves.master),
      red: lerpPoints(state.curves.red),
      green: lerpPoints(state.curves.green),
      blue: lerpPoints(state.curves.blue),
    },
    wheels: {
      lift: {
        x: state.wheels.lift.x * t,
        y: state.wheels.lift.y * t,
        luma: state.wheels.lift.luma * t,
      },
      gamma: {
        x: state.wheels.gamma.x * t,
        y: state.wheels.gamma.y * t,
        luma: state.wheels.gamma.luma * t,
      },
      gain: {
        x: state.wheels.gain.x * t,
        y: state.wheels.gain.y * t,
        luma: state.wheels.gain.luma * t,
      },
    },
  };
}
